"""Phase 1 — regenerate the area-selection evidence. Metadata only; downloads no spikes.

    python scripts/run_phase1.py

Writes results/phase1_summary.md and results/phase1_sessions.csv.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.data.access import get_one, units_table  # noqa: E402
from src.data.select_areas import (  # noqa: E402
    best_sessions,
    cooccurrence_sweep,
    region_set_frequency,
    session_trial_counts,
    top_unconstrained_sessions,
)

MIN_UNITS = 20
MIN_TRIALS = 200


def _fmt(df: pd.DataFrame) -> str:
    return df.to_markdown(index=False)


def main() -> None:
    axis = yaml.safe_load((ROOT / "config" / "areas.yaml").read_text())["candidate_axis"]

    one = get_one()
    units = units_table(one)
    trials = session_trial_counts(one)

    sweep_axis = cooccurrence_sweep(units, axis)
    sessions = best_sessions(
        units, axis, trial_counts=trials,
        min_units_per_region=MIN_UNITS, min_regions_per_session=2, min_trials=MIN_TRIALS,
    )
    pairs = region_set_frequency(units, axis, set_size=2, min_units_per_region=MIN_UNITS)
    triplets = region_set_frequency(units, axis, set_size=3, min_units_per_region=MIN_UNITS)
    unconstrained = top_unconstrained_sessions(units, min_units_per_region=MIN_UNITS, top_n=8)
    unconstrained = unconstrained.merge(trials, on="eid", how="left")

    out_dir = ROOT / "results"
    out_dir.mkdir(exist_ok=True)
    sessions.to_csv(out_dir / "phase1_sessions.csv", index=False)

    def compose(df):
        return df.assign(
            composition=lambda d: [", ".join(f"{a}:{b}" for a, b in zip(r, u))
                                   for r, u in zip(d.regions, d.units)]
        ).drop(columns=["regions", "units"])

    md = f"""# Phase 1 — area selection (generated by `scripts/run_phase1.py`)

Metadata only. Units: the paper's frozen set ({len(units):,} units,
{units.Beryl.nunique()} Beryl regions, {units.eid.nunique()} sessions).

Thresholds: >= {MIN_UNITS} good units per region, >= {MIN_TRIALS} usable trials per session.

## 1. Threshold sensitivity, candidate axis

Axis: {", ".join(axis)}

{_fmt(sweep_axis)}

## 2. Qualifying sessions on the axis ({len(sessions)} total)

{_fmt(compose(sessions.head(10)))}

## 3. Recurring region combinations (sessions as replicates)

### Pairs
{_fmt(pairs.head(8))}

### Triplets
{_fmt(triplets.head(8))}

## 4. Best simultaneous coverage across ALL Beryl regions

Does the axis limit us, or does the dataset?

{_fmt(compose(unconstrained))}
"""
    (out_dir / "phase1_summary.md").write_text(md, encoding="utf-8")
    print(f"wrote {out_dir/'phase1_summary.md'}")
    print(f"wrote {out_dir/'phase1_sessions.csv'}  ({len(sessions)} sessions)")


if __name__ == "__main__":
    main()
